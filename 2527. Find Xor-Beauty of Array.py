# 解题思路:
# 数学结论：所有三元组((nums[i]|nums[j])&nums[k])的异或结果等于数组中所有元素异或。
# 对于每个比特位，三元组中只有i=j=k时该位的贡献在异或中出现奇数次。
# 因此O(N^3)问题降为O(N)异或操作。
#
# 时间复杂度: O(N)
# 空间复杂度: O(1)
#
# 关键点:
# - 核心结论：xorBeauty(nums) = XOR of all elements
# - 证：对于每个bit位，考虑所有三元组的贡献，只有三个下标相同时奇数次
