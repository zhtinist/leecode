# 解题思路:
# 切比雪夫距离不超过 k 的区域是一个边长为 2k+1 的正方形。因此问题转化为：
# 用边长为 (2k+1) 的正方形覆盖 n*m 的矩形，最少需要多少个正方形。
# 行方向：至少需要 ceil(n / (2k+1)) 个传感器覆盖所有行；
# 列方向：至少需要 ceil(m / (2k+1)) 个传感器覆盖所有列。
# 将它们放在网格交点处即可达到理论下界，故答案为乘积。
#
# 时间复杂度: O(1)
# 空间复杂度: O(1)
#
# 关键点:
# - 切比雪夫距离覆盖范围 = 正方形
# - ceil 除法公式：(a + b - 1) // b
# - 行和列方向独立，结果相乘
