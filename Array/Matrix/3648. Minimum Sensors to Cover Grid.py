"""
LeetCode #3648 - Minimum Sensors to Cover Grid
覆盖网格的最少传感器数目
https://leetcode.cn/problems/minimum-sensors-to-cover-grid/

给你一个 `n × m` 的网格和一个整数 `k`。
一个放置在单元格 `(r, c)` 的传感器可以覆盖所有与 `(r, c)` 的 切比雪夫距离不超过 `k` 的单元格。
两个单元格 `(r_1, c_1)` 和 `(r_2, c_2)` 之间的 切比雪夫距离 为 `max(|r_1 − r_2|,|c_1 − c_2|)`。
你的任务是返回覆盖整个网格所需传感器的 最少 数量。

示例 1:

输入: n = 5, m = 5, k = 1
输出: 4
解释:
在位置 `(0, 3)`、`(1, 0)`、`(3, 3)` 和 `(4, 1)` 放置传感器可以确保网格中的每个单元格都被覆盖。因此，答案是 4。
示例 2:

输入: n = 2, m = 2, k = 2
输出: 1
解释:
当 `k = 2` 时，无论传感器放在哪个位置，单个传感器都可以覆盖整个 `2 * 2` 的网格。因此，答案是 1。

提示:
`1 <= n <= 10^3`
`1 <= m <= 10^3`
`0 <= k <= 10^3`
"""

from typing import List, Optional


class Solution:
    def minSensors(self, n: int, m: int, k: int) -> int:
        """
        一个传感器覆盖以它为中心的边长为 2k+1 的正方形区域（切比雪夫距离）。
        要在行方向覆盖 n 行，每行需要 ceil(n / (2k+1)) 个传感器；
        列方向同理。最少数目为两者的乘积。
        """
        size = 2 * k + 1
        rows_needed = (n + size - 1) // size
        cols_needed = (m + size - 1) // size
        return rows_needed * cols_needed










