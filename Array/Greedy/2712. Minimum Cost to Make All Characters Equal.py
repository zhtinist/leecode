# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Greedy, String, Dynamic Programming
#
# 解题思路:
# 遍历相邻字符对，当 s[i] != s[i-1] 时需要在这个位置"切开"。
# 可以选择前缀反转（成本 i）或后缀反转（成本 n-i），取两者最小值累加。
# 因为每次操作可以在切分处独立选择方向，贪心取最小成本即可得到全局最优。
#
# 时间复杂度: O(n)
# 空间复杂度: O(1)
#
# 关键点:
# - 只需关注相邻字符不同的位置（切分点）
# - 每个切分点独立决策：前缀操作成本为 i，后缀操作成本为 n-i
# - 答案不会超过 n^2，因此 Python 的 int 足够存储
