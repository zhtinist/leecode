#
# 解题思路:
# 将数组排序后，最小的 n/3 个元素作为每组的最小值（被丢弃），剩下的 2n/3 个元素
# 两两配对，前者作为中位数，后者作为最大值。为了最大化中位数之和，中位数应取
# 索引 n/3, n/3+2, n/3+4, ..., n-2 的位置上的元素。
# 例如：排序后 [a,b,c,d,e,f]（n=6），分组为 (a,c,d), (b,e,f)，中位数为 c 和 e，
# 即索引 2 和 4，恰好是 n/3=2 开始每隔两个元素。
#
# 时间复杂度: O(n log n) — 排序开销
# 空间复杂度: O(1) — 仅使用常数额外空间（忽略排序栈空间）
#
# 关键点:
# - 排序后中位数位置的公式：i = n/3, i += 2
# - 贪心策略确保最小值被舍弃，中位数取较大的那一半
