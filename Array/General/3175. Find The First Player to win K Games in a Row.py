# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Array, Simulation
#
# 解题思路:
# 模拟比赛过程。维护当前胜者和连胜次数。从索引1开始依次挑战当前胜者：
# 如果胜者技能更高，连胜+1；否则新挑战者成为胜者，连胜重置为1。
# 一旦某玩家连胜k场立即返回。如果遍历完所有玩家仍未有人连胜k场，
# 则拥有最大技能的玩家必然最终获胜（它能打败所有人）。
#
# 时间复杂度: O(n)
# 空间复杂度: O(1)
#
# 关键点:
# - 只需一次遍历即可模拟
# - 技能值互不相同保证了唯一胜负
# - 遍历完一轮后技能最高的玩家必胜
