"""
LeetCode #3818 - Minimum Prefix Removal to Make Array Strictly Increasing
移除前缀使数组严格递增
https://leetcode.cn/problems/minimum-prefix-removal-to-make-array-strictly-increasing/

给你一个整数数组 `nums`。
你需要从 `nums` 中 恰好 移除一个前缀（可以为空）。
返回一个整数，表示被移除的前缀的 最小 长度，使得剩余的数组 严格递增 。
数组的 前缀 是从数组的起始位置开始，一直延伸到任意位置的子数组。
如果一个数组的每个元素都严格大于它的前一个元素（若存在），则称该数组 严格递增 。

示例 1：

输入： nums = [1,-1,2,3,3,4,5]
输出： 4
解释：
移除前缀 `prefix = [1, -1, 2, 3]` 后，剩余数组为 `[3, 4, 5]`，严格递增。
示例 2：

输入： nums = [4,3,-2,-5]
输出： 3
解释：
移除前缀 `prefix = [4, 3, -2]` 后，剩余数组为 `[-5]`，严格递增。
示例 3：

输入： nums = [1,2,3,4]
输出： 0
解释：
数组 `nums = [1, 2, 3, 4]` 已经是严格递增的，因此移除空前缀即可。

提示：
`1 <= nums.length <= 10^5`
`-10^9 <= nums[i] <= 10^9​​​​​​​`
"""

from typing import List, Optional


class Solution:
    def minimumPrefixRemoval(self, nums: List[int]) -> int:
        """
        移除前缀使剩余数组严格递增。
        从右向左扫描找到最长的严格递增后缀。
        返回移除的前缀长度 = 该后缀起始位置。
        """
        n = len(nums)
        if n <= 1:
            return 0

        # 从右向左找最长严格递增后缀
        # 后缀从 idx 开始需要满足 nums[idx] < nums[idx+1] < ... < nums[n-1]
        idx = n - 1
        while idx > 0 and nums[idx - 1] < nums[idx]:
            idx -= 1

        # idx 是严格递增后缀的起始位置
        # 需要移除的前缀长度 = idx（移除 [0, idx-1]）
        return idx










