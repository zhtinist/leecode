# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Array
#
# 解题思路:
# 要移除一个前缀使剩余数组严格递增，关键是找到最长的严格递增后缀。
# 因为移除前缀不影响剩余部分的顺序关系，剩余部分必须自身就是严格递增的。
#
# 从右向左遍历数组：
# - 如果 nums[i-1] < nums[i]，说明 i-1 到 i 是递增的，继续向左检查
# - 如果 nums[i-1] >= nums[i]，说明在 i-1 处递增性被破坏，
#   由于只能移除前缀，i-1 必须被移除，停止扫描
#
# 最终找到的 idx 就是严格递增后缀的起始位置（第一个满足递增条件的位置）。
# 需要移除的前缀长度就是 idx（即移除下标 [0, idx-1] 的元素）。
# 如果整个数组已经是严格递增的，idx = 0，不需要移除任何元素。
#
# 时间复杂度: O(N)，只需从右向左遍历一次。
# 空间复杂度: O(1)，只使用常数级额外空间。
#
# 关键点:
# - "只能移除前缀"意味着剩余部分是原数组的一个后缀
# - 从右向左扫描找到最长严格递增后缀
# - 边界情况：空数组或单元素数组返回 0
