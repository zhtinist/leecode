# 解题思路:
# 递归遍历数组元素。如果当前元素是列表且当前深度小于n，则递归展平（深度+1）；
# 否则直接加入结果。这与JavaScript的Array.flat(n)功能等价，但不能使用内置flat方法。
#
# 时间复杂度: O(N) 其中N是数组总元素个数
# 空间复杂度: O(N + D) 其中D是递归深度
#
# 关键点:
# - 递归时追踪深度参数depth
# - 只有当深度<n时才展开子数组
# - 非列表元素直接追加到结果中
