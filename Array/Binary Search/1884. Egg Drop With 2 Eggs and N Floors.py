# 数学方法：有两枚鸡蛋时的最优策略如下：
# 第一次从第 k 层扔，如果碎了，用第二枚从 1 到 k-1 逐层尝试，
# 最坏需要 k 次。如果没碎，下一次从 k+(k-1) 层扔，依次类推。
# 覆盖的总楼层数为 k + (k-1) + ... + 1 = k(k+1)/2。
# 因此需要找到最小的 k 使得 k(k+1)/2 >= n。
# 使用二分查找即可。
#
# 时间复杂度: O(log n) — 二分查找
# 空间复杂度: O(1) — 常数空间
