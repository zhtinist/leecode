#
# Difficulty: Medium
# Tags: Greedy, Array, Binary Search
#
# 解题思路:
# 本题要求最小化青蛙往返路径（去程 + 回程）中的最大跳跃长度，且每块石头最多到达一次。
# 可以将问题看作将石头分成两条路径：去程（索引递增）和回程（索引递减），共同覆盖所有石头。
#
# 核心策略：将石头按索引奇偶性交替分配给两条路径。
# - 去程路径：stones[0], stones[2], stones[4], ... 直到 stones[n-1]
# - 回程路径：stones[n-1], stones[n-3], stones[n-5], ..., stones[1], stones[0]
# 这样每条路径上相邻石头的索引间隔最多为 2，最大跳跃长度即为 max(stones[i] - stones[i-2])。
#
# 为什么这是最优的？考虑任意三个连续石头 stones[i-2], stones[i-1], stones[i]：
# 根据鸽巢原理，三条石头中至少有两条属于同一条路径，因此必然存在索引间隔 >= 2
# 的相邻石头对，其跳跃长度至少为 stones[i] - stones[i-2]。所以答案不可能小于
# max(stones[i] - stones[i-2])。而交替分配方案恰好达到了这个下界。
#
# 时间复杂度: O(n) — 遍历一次数组
# 空间复杂度: O(1) — 只使用常数额外空间
#
# 关键点:
# - 石头按索引奇偶交替分配给去程和回程，最小化每条路径的最大跳跃
# - 答案等于 max(stones[i] - stones[i-2])，i 从 2 到 n-1
# - 需要单独处理 n=2 的情况，此时答案为 stones[1] - stones[0]
# - 去程和回程的端点石头（首尾）分别出现在两条路径中，不计入"最多一次"的限制
