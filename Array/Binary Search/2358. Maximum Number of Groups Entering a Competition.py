#
# 解题思路:
# 关键在于理解分组条件：各组人数必须严格递增。最优策略是让各组人数分别为 1, 2, 3, ..., k。
# 这样能在总人数 n 的限制下得到最多的组数 k。
# 需要满足：1 + 2 + 3 + ... + k = k*(k+1)/2 <= n。
# 解不等式 k^2 + k - 2n <= 0，得到 k = floor((-1 + sqrt(1 + 8n)) / 2)。
# 由于成绩可以任意分配到各组（排序后从小到大分配），总能满足总成绩递增的条件。
#
# 时间复杂度: O(1)
# 空间复杂度: O(1)
#
# 关键点:
# - 贪心策略：组大小必须严格递增，直接取 1, 2, 3, ... 即可最大化组数
# - 求解一元二次不等式得到闭合公式
# - 成绩数值本身不重要，只需关注总人数 n
