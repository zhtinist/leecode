#
# Difficulty: Medium
# Tags: Greedy, Memoization, String, Dynamic Programming
#
# 解题思路:
# 采用贪心策略，从右向左（即从最低位到最高位）扫描字符串 s。对于每个字符：
# - 如果是 '0'，它不贡献任何数值，但可以增加子序列长度，所以始终选入。
# - 如果是 '1'，检查将它放在当前已构建子序列的最高位（即第 length 位，贡献 2^length）
#   后，总值是否仍 ≤ k。如果是则选入，否则跳过。
# 该贪心策略的正确性在于：我们希望子序列尽可能长，而 '0' 总是有益的；对于 '1'，
# 在最低位出现的 '1' 贡献更小，优先选入低位的 '1' 比高位的 '1' 更优。从右向左处理
# 恰好保证了这一点。
# 优化：当 length ≥ 31 时，2^31 > 2×10^9 > k，之后的所有 '1' 都不可能被选入，
# 可以提前剪枝（只统计剩余的 '0'）。
#
# 时间复杂度: O(n)，其中 n = len(s)，只需一次从右向左的扫描。
# 空间复杂度: O(1)，只使用常数级额外变量。
#
# 关键点:
# - 从右向左贪心（LSB 到 MSB），低位 '1' 优先于高位 '1'。
# - '0' 永远可以选入，因为它不增加数值。
# - 当位数超过 30 时，对应的 2^length 必然超过 k (≤ 10^9)，可以安全跳过所有后续 '1'。
