"""
LeetCode #2311 - Longest Binary Subsequence Less Than or Equal to K
小于等于 K 的最长二进制子序列
https://leetcode.cn/problems/longest-binary-subsequence-less-than-or-equal-to-k/

给你一个二进制字符串 `s` 和一个正整数 `k` 。
请你返回 `s` 的 最长 子序列的长度，且该子序列对应的 二进制 数字小于等于 `k` 。
注意：
子序列可以有 前导 0 。
空字符串视为 `0` 。
子序列 是指从一个字符串中删除零个或者多个字符后，不改变顺序得到的剩余字符序列。

示例 1：
输入：s = "1001010", k = 5 输出：5 解释：s 中小于等于 5 的最长子序列是 "00010" ，对应的十进制数字是 2 。 注意 "00100" 和 "00101" 也是可行的最长子序列，十进制分别对应 4 和 5 。 最长子序列的长度为 5 ，所以返回 5 。
示例 2：
输入：s = "00101001", k = 1 输出：6 解释："000001" 是 s 中小于等于 1 的最长子序列，对应的十进制数字是 1 。 最长子序列的长度为 6 ，所以返回 6 。

提示：
`1 <= s.length <= 1000`
`s[i]` 要么是 `'0'` ，要么是 `'1'` 。
`1 <= k <= 10^9`
"""

from typing import List, Optional


class Solution:
    def longestSubsequence(self, s: str, k: int) -> int:
        value = 0
        length = 0

        # 从右向左遍历（从最低位到最高位）
        for i in range(len(s) - 1, -1, -1):
            if s[i] == '0':
                # '0' 不增加数值，总是可以选入子序列
                length += 1
            else:  # s[i] == '1'
                # 当 length >= 31 时，2^length > 10^9 >= k，永远无法再选 '1'
                if length >= 31:
                    continue
                bit_val = 1 << length
                if value + bit_val <= k:
                    value += bit_val
                    length += 1
                # 否则跳过这个 '1'

        return length


