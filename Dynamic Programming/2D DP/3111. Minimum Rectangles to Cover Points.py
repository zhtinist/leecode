# Solution & Explanation
# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Greedy, Array, Sorting
#
# 解题思路:
# y坐标不影响矩形数量（矩形可以向上无限延伸，底部始终在y=0），只需关注x坐标。
# 将所有点的x坐标去重排序，贪心覆盖：从最左端开始，用一个宽度为w的矩形覆盖
# 尽可能多的点，然后从下一个未覆盖点开始新的矩形，直到所有点被覆盖。
#
# 时间复杂度: O(n log n)
# 空间复杂度: O(n)
#
# 关键点:
# - y坐标无关，只需考虑x坐标
# - 贪心策略：每个矩形尽量向右延伸w宽度
# - 去重后排序，从最小x开始覆盖
