# Solution & Explanation
# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Paid Only: No
#
# 解题思路:
# 动态规划（DP）：
# 1. 定义 dp[i] 为覆盖前 i 天所需的最低花费（i 从 1 到 last_day）。
# 2. 遍历每一天 i：
#    - 如果第 i 天不需要旅行，则 dp[i] = dp[i-1]（不需要买票）。
#    - 如果第 i 天需要旅行，尝试三种购票方式，取最小值：
#      * 买 1 天票：dp[i-1] + costs[0]
#      * 买 7 天票：dp[i-7] + costs[1]（票覆盖第 i-6 到第 i 天）
#      * 买 30 天票：dp[i-30] + costs[2]（票覆盖第 i-29 到第 i 天）
#      使用 max(0, i-x) 防止索引越界。
# 3. 最终答案在 dp[last_day]。
#
# 时间复杂度: O(W)，W = days[-1]（最大日期 <= 365），每天只处理一次
# 空间复杂度: O(W)，dp 数组大小。可优化为 O(30) 使用滚动数组
#
# 关键点:
# - 不需要旅行的日子不需要买票，dp[i] = dp[i-1]
# - 状态转移考虑三种票的有效期（1天、7天、30天）
# - 使用 day_set 快速判断某天是否需要旅行
# - 边界处理：i - 7 或 i - 30 可能为负数，用 max(0, ...) 处理
