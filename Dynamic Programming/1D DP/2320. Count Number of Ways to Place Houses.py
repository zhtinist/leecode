"""
LeetCode #2320 - Count Number of Ways to Place Houses
统计放置房子的方式数
https://leetcode.cn/problems/count-number-of-ways-to-place-houses/

一条街道上共有 `n * 2` 个 地块 ，街道的两侧各有 `n` 个地块。每一边的地块都按从 `1` 到 `n` 编号。每个地块上都可以放置一所房子。
现要求街道同一侧不能存在两所房子相邻的情况，请你计算并返回放置房屋的方式数目。由于答案可能很大，需要对 `10^9 + 7` 取余后再返回。
注意，如果一所房子放置在这条街某一侧上的第 `i` 个地块，不影响在另一侧的第 `i` 个地块放置房子。

示例 1：
输入：n = 1 输出：4 解释： 可能的放置方式： 1. 所有地块都不放置房子。 2. 一所房子放在街道的某一侧。 3. 一所房子放在街道的另一侧。 4. 放置两所房子，街道两侧各放置一所。
示例 2：
输入：n = 2 输出：9 解释：如上图所示，共有 9 种可能的放置方式。

提示：
`1 <= n <= 10^4`
"""

from typing import List, Optional


class Solution:
    def countHousePlacements(self, n: int) -> int:
        MOD = 10 ** 9 + 7

        # dp[i] = 单侧 i 个地块的合法放置方式数
        # dp[0] = 1 (全空), dp[1] = 2 (空/放)
        # 递推：dp[i] = dp[i-1] + dp[i-2]
        #   - 第 i 块不放：dp[i-1] 种方式
        #   - 第 i 块放：则第 i-1 块必须空，有 dp[i-2] 种方式
        prev2, prev1 = 1, 2  # dp[0], dp[1]
        for i in range(2, n + 1):
            prev2, prev1 = prev1, (prev2 + prev1) % MOD

        # prev1 现在是 dp[n]（单侧 n 个地块的方式数）
        one_side = prev1
        # 两侧独立，总方式数 = (单侧方式数)^2
        return (one_side * one_side) % MOD


# ═══════════════════════════════════════════════════════════════════════════════
# Solution & Explanation
# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Dynamic Programming
#
# 解题思路:
# 两侧相互独立，因此总方式数 = (单侧 n 个地块的方式数)^2。
#
# 对于单侧 n 个地块，问题等价于：求长度为 n 的二进制串中，没有相邻 1 的个数。
# 这是经典的斐波那契型 DP：
#   dp[0] = 1  （0 个地块，只有一种方式：全空）
#   dp[1] = 2  （1 个地块：空 或 放）
#   dp[i] = dp[i-1] + dp[i-2]
#     解释：第 i 块不放 → dp[i-1]；第 i 块放 → 第 i-1 块必须空 → dp[i-2]
#
# 因此 dp[n] = Fib(n+2)，其中 Fib(1)=1, Fib(2)=1, Fib(3)=2, ...
# 最终答案 = dp[n]^2 mod (10^9+7)
#
# 时间复杂度: O(n)，一次线性递推到 n。
# 空间复杂度: O(1)，只使用两个滚动变量。
#
# 关键点:
# - 两侧独立 → 答案 = 单侧方案数的平方。
# - 单侧问题即"无相邻 1 的二进制串计数"（斐波那契递推）。
# - 使用滚动变量节省空间，全程取模防溢出。
