#
# 解题思路:
# 1. 分析两种操作对 '1' 数量的影响：
#    - 操作1（0→1）：增加一个 1，cost=1
#    - 操作2（11→00）：减少两个相邻的 1，cost=1
# 2. 按位置分类差异：
#    - 需要添加 1 的位置（s1='0', s2='1'）：每个直接用操作1解决
#    - 需要移除 1 的位置（s1='1', s2='0'）：需要操作2，配对处理
# 3. 移除策略：扫描连续的需要移除 1 的块：
#    - 块长度为偶数：两两配对，每对一次操作2，cost = length/2
#    - 块长度为奇数：配对后剩一个，需"借用"相邻位置（先操作1创建
#      临时伙伴，再操作2一起删除，最后操作1恢复邻居），cost = 2
# 4. 总 cost = 添加操作数 + 所有移除块的处理成本
# 5. 唯一不可行情况：单字符且需要移除（无邻居可借用），返回 -1
#
# 时间复杂度: O(n)，一次线性扫描
# 空间复杂度: O(1)
#
# 关键点:
# - 将移除 1 的需求按连续块处理：相邻的两个移除只需一次操作2
# - 单独的移除需要"借用邻居"：操作1 + 操作2 + 操作1（恢复）= 3 次？
#   实际上只需 2 次额外操作（借用并还原邻居），由于邻居本身不变
# - 单字符无邻居的特殊情况需要返回 -1
