# Difficulty: Medium
# Tags: Array, Divide and Conquer, Matrix
#
# 解题思路:
# 1. 递归构建特殊网格
# 2. 基础情况 N=0：1x1 网格 [[0]]
# 3. 对 N>0，先生成 N-1 的子网格（大小 s = 2^(N-1)）
# 4. 将四个象限分配数字：
#    - 右上角 (TR)：子网格 + 0 * s^2（最小数字）
#    - 右下角 (BR)：子网格 + 1 * s^2
#    - 左下角 (BL)：子网格 + 2 * s^2
#    - 左上角 (TL)：子网格 + 3 * s^2（最大数字）
# 5. 这保证了 TR < BR < BL < TL 的集合大小关系
#    且每个象限递归满足特殊网格性质
#
# 时间复杂度: O(4^N) = O(2^(2N))
# 空间复杂度: O(4^N)
#
# 关键点:
# - 四象限编号：TR=0, BR=1, BL=2, TL=3
# - 递归保持每个象限内也是特殊网格
# - N <= 10，最大网格 1024x1024，约 1M 单元格
