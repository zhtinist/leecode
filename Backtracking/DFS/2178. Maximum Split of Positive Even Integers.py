"""
LeetCode #2178 - Maximum Split of Positive Even Integers
拆分成最多数目的正偶数之和
https://leetcode.cn/problems/maximum-split-of-positive-even-integers/

给你一个整数 `finalSum` 。请你将它拆分成若干个 互不相同 的正偶数之和，且拆分出来的正偶数数目 最多 。
比方说，给你 `finalSum = 12` ，那么这些拆分是 符合要求 的（互不相同的正偶数且和为 `finalSum`）：`(2 + 10)` ，`(2 + 4 + 6)` 和 `(4 + 8)` 。它们中，`(2 + 4 + 6)` 包含最多数目的整数。注意 `finalSum` 不能拆分成 `(2 + 2 + 4 + 4)` ，因为拆分出来的整数必须互不相同。
请你返回一个整数数组，表示将整数拆分成 最多 数目的正偶数数组。如果没有办法将 `finalSum` 进行拆分，请你返回一个 空 数组。你可以按 任意 顺序返回这些整数。

示例 1：
输入：finalSum = 12 输出：[2,4,6] 解释：以下是一些符合要求的拆分：`(2 + 10)，``(2 + 4 + 6) `和 `(4 + 8) 。` (2 + 4 + 6) 为最多数目的整数，数目为 3 ，所以我们返回 [2,4,6] 。 [2,6,4] ，[6,2,4] 等等也都是可行的解。
示例 2：
输入：finalSum = 7 输出：[] 解释：没有办法将 finalSum 进行拆分。 所以返回空数组。
示例 3：
输入：finalSum = 28 输出：[6,8,2,12] 解释：以下是一些符合要求的拆分：`(2 + 26)，``(6 + 8 + 2 + 12)` 和 `(4 + 24) 。` `(6 + 8 + 2 + 12)` 有最多数目的整数，数目为 4 ，所以我们返回 [6,8,2,12] 。 [10,2,4,12] ，[6,2,4,16] 等等也都是可行的解。

提示：
`1 <= finalSum <= 10^10`
"""

from typing import List, Optional


class Solution:
    def maximumEvenSplit(self, finalSum: int) -> List[int]:
        """
        贪心法：如果 finalSum 是奇数，无法拆分成偶数之和，直接返回空列表。
        如果是偶数，从小到大依次取偶数 2, 4, 6, ...，
        只要剩余和大于当前偶数的两倍，就继续取下一个偶数；
        否则将剩余和整体加入结果（确保不重复且所有数互不相同）。
        """
        if finalSum % 2 == 1:
            return []

        result = []
        cur = 2  # 当前要尝试的正偶数
        while finalSum > 0:
            # 只有在剩余和 > 2 * cur 时才取 cur，
            # 这样保证取了 cur 之后，剩余的和还能用更大的偶数继续拆分
            if finalSum - cur > cur:
                result.append(cur)
                finalSum -= cur
                cur += 2
            else:
                # 剩余和作为最后一个元素，保证与前边所有数都不同
                result.append(finalSum)
                break
        return result


