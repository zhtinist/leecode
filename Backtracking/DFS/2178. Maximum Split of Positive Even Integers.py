#
# Difficulty: Medium
# Tags: Greedy, Math, Backtracking
#
# 解题思路:
# 1. 如果 finalSum 是奇数，直接返回空列表，因为奇数不可能拆分成偶数之和。
# 2. 从小到大贪心地取偶数 2, 4, 6, ... 作为候选：
#    - 只要 剩余和 - 当前偶数 > 当前偶数（即剩余和 > 2 * 当前偶数），
#      说明取了当前偶数后还能继续拆出更大的互不相同的偶数，就取当前偶数。
#    - 否则，将剩余和整体加入结果列表作为最后一个元素并结束循环。
#    这样保证了结果中的偶数互不相同，且数目最大化。
# 3. 返回结果列表。
#
# 时间复杂度: O(sqrt(finalSum))
# - 最坏情况下需要遍历大约 sqrt(2*finalSum) 个偶数。
#
# 空间复杂度: O(sqrt(finalSum))
# - 结果列表大小约为 sqrt(finalSum) 级别。
#
# 关键点:
# - 奇数不可拆分，直接返回 []。
# - 贪心条件 `finalSum - cur > cur` 保证始终能拆出更大的偶数。
# - 最后一个元素直接取剩余和，避免冲突。
