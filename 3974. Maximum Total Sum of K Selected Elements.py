# Solution & Explanation
# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Greedy, Array, Sorting
#
# 解题思路:
# 1. 首先选择数组中最大的 k 个元素（排序后取前 k 个）。
# 2. 处理顺序可以任意安排。由于每处理一个元素 mul 减 1，
#    可用的乘数依次为 mul, mul-1, ..., mul-k+1（降序）。
# 3. 根据排序不等式（Rearrangement Inequality），将较大的乘数分配给
#    较大的元素可以最大化总和。
# 4. 对每个元素，决策是"乘"还是"加"：
#    - 若当前乘数 > 1，乘法收益更大（nums[i] * cur_mul > nums[i]）
#    - 若当前乘数 <= 1（包括 0 和负数），直接加元素值更优
# 5. 按降序遍历选中的 k 个元素，累加贡献即可。
#
# 时间复杂度: O(N log N)，主要来自排序
# 空间复杂度: O(1) 或 O(N)（排序可能需要额外空间）
#
# 关键点:
# - 排序不等式保证大乘数配大元素是最优策略
# - 当乘数 <= 1 时应选择直接相加
# - 处理顺序不影响结果（只要乘数和元素的配对正确）
