# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Stack, Greedy, Array, Hash Table, Monotonic Stack
#
# 解题思路:
# 1. 操作是从子数组中移除最小值（设为 0），每次处理一个数值层级
# 2. 维护一个单调栈，存储当前"活跃"的值（递增序列）
# 3. 遍历数组：
#    - 遇到比栈顶小的值：弹出栈顶（那些较大的值层已经被"关闭"）
#    - 遇到比栈顶大的正值：新增一层操作，入栈并计数
#    - 遇到等于栈顶或为 0 的值：不新增操作
# 4. 栈中元素的数量变化即对应操作次数
#
# 时间复杂度: O(n)
# 空间复杂度: O(n)
#
# 关键点:
# - 每次操作移除的是子数组中的最小值，所以处理顺序必须从小到大
# - 单调栈模拟了"高度层"的概念
# - 遇到更小值说明之前的大值层已经无法继续覆盖当前区域
