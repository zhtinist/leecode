# Solution & Explanation
# ═══════════════════════════════════════════════════════════════════════════════
#
# Difficulty: Medium
# Tags: Bit Manipulation, Array, Math
#
# 解题思路:
# 分析操作 num[i] = num[i] AND (num[i] XOR x)：
# 对于 num[i] 中的每个二进制位——
# - 若该位为 0：AND 任何值后仍为 0，所以无法将 0 变成 1。
# - 若该位为 1：可以通过选择合适的 x 将该位保留为 1（令 x 在该位为 0）
#   或变为 0（令 x 在该位为 1）。
#
# 即：每个数字可以独立地将其任意为 1 的位变成 0，但无法将 0 变成 1。
# 换言之，最终的每个 num[i] 可以是其原始值的任意"子掩码"（subset of bits）。
#
# 对于异或和：若某一位上至少有一个数字的原始值为 1，我们可以保留那个数字的该位为 1，
# 同时将其他所有数字的该位变为 0。这样异或结果在该位就是 1（奇数个 1）。
# 若所有数字的某一位都为 0，则该位在最终异或和中必然为 0。
#
# 因此，最大异或和 = 所有数字的按位或（OR）结果。每一位只要能出现在至少一个
# 数字中，就可以独立地贡献到最终异或和中。
#
# 时间复杂度: O(n)，一次遍历求所有元素的按位或。
# 空间复杂度: O(1)，只使用常数级额外变量。
#
# 关键点:
# - 操作只能将 1 变成 0，不能将 0 变成 1（即每个数只能失去位，不能获得位）。
# - 每位在异或和中独立：只要某位在至少一个数中为 1，就能使最终异或和的该位为 1。
# - 答案 = 所有 nums[i] 的按位或。
