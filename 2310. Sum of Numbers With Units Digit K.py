"""
LeetCode #2310 - Sum of Numbers With Units Digit K
个位数字为 K 的整数之和
https://leetcode.cn/problems/sum-of-numbers-with-units-digit-k/

给你两个整数 `num` 和 `k` ，考虑具有以下属性的正整数多重集：
每个整数个位数字都是 `k` 。
所有整数之和是 `num` 。
返回该多重集的最小大小，如果不存在这样的多重集，返回 `-1` 。
注意：
多重集与集合类似，但多重集可以包含多个同一整数，空多重集的和为 `0` 。
个位数字 是数字最右边的数位。

示例 1：
输入：num = 58, k = 9 输出：2 解释： 多重集 [9,49] 满足题目条件，和为 58 且每个整数的个位数字是 9 。 另一个满足条件的多重集是 [19,39] 。 可以证明 2 是满足题目条件的多重集的最小长度。
示例 2：
输入：num = 37, k = 2 输出：-1 解释：个位数字为 2 的整数无法相加得到 37 。
示例 3：
输入：num = 0, k = 7 输出：0 解释：空多重集的和为 0 。

提示：
`0 <= num <= 3000`
`0 <= k <= 9`
"""

from typing import List, Optional


class Solution:
    def minimumNumbers(self, num: int, k: int) -> int:
        # 空多重集和为 0
        if num == 0:
            return 0

        # 如果 num 本身个位数字就是 k，用一个数 num 自身即可
        if num % 10 == k:
            return 1

        # 个位数字为 k 的正整数中最小的那个
        # k == 0: 最小的个位为 0 的正整数是 10
        # k > 0:  最小的个位为 k 的正整数是 k 本身
        min_num = 10 if k == 0 else k

        # 枚举多重集的大小 n
        # n 个这样的数之和的个位数字必定是 (n * k) % 10
        # n 个这样的数的最小可能总和是 n * min_num
        # 如果 n * min_num > num，之后 n 更大的情况最小总和更大，不可能满足
        for n in range(1, num + 1):
            # 检查个位数字是否匹配
            if (n * k) % 10 != num % 10:
                continue
            # 检查最小可能总和是否不超过 num
            if n * min_num > num:
                break
            # 条件满足：个位数字匹配 且 最小值约束满足
            return n

        return -1


