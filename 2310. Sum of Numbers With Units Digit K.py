#
# 1. 特殊情况处理：
#    - 若 num == 0，空多重集和为 0，返回 0。
#    - 若 num % 10 == k，则 {num} 本身就是合法多重集，大小为 1。
#
# 2. 一般情况（需要 n >= 1 个数）：
#    - 设最小个位为 k 的正整数为 min_num：k == 0 时为 10，否则为 k。
#    - n 个满足条件的数的和，其个位数字必为 (n * k) % 10。
#      因为每个数的个位贡献 k，十位及以上不影响个位。
#    - n 个这样的数的最小可能总和为 n * min_num（全部取最小值）。
#    - 只要个位数字匹配且最小总和 <= num，就一定能构造出和为 num 的 n 个数：
#      先用 (n-1) 个 min_num 和一个 num - (n-1)*min_num，
#      后者个位也是 k（因为个位数字条件保证了这一点），且它 >= min_num。
#
# 3. 从小到大枚举 n，第一个满足条件的 n 就是最小大小。
#
# 时间复杂度: O(num)
# - 枚举 n 从 1 到最多 num（实际可进一步缩小到 num/min_num）
#
# 空间复杂度: O(1)
# - 只使用了常数个变量
#
# 关键点:
# - 个位数字约束转化为 (n * k) % 10 == num % 10
# - 最小值约束: n * min_num <= num
# - 两个条件同时满足即可构造，无需实际构造多重集
# - k == 0 时最小的正数个位为 0 是 10，不是 0
