# 解题思路:
# 线性扫描所有塔，对每个塔计算其与 center 的曼哈顿距离。
# 曼哈顿距离公式：|x_i - cx| + |y_i - cy|。
# 如果距离 <= radius，则该塔可到达。
# 在所有可到达的塔中，维护质量因子最大的塔坐标。
# 如果两个塔质量因子相同，按字典序选择更小的坐标：
#   先比较 x 坐标，x 小的优先；x 相同则比较 y 坐标。
# 如果没有可到达的塔，返回 [-1, -1]。
#
# 时间复杂度: O(N)，遍历所有塔一次。
# 空间复杂度: O(1)，只使用常数级额外空间。
#
# 关键点:
# - 曼哈顿距离与欧几里得距离的区别：曼哈顿距离 = |dx| + |dy|
# - 字典序比较：先比 x 后比 y
# - 初始 best_quality = -1 可以自然地处理没有可到达塔的情况
