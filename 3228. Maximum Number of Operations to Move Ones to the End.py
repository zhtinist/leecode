# Difficulty: Medium
# Tags: Greedy, String, Counting
#
# 解题思路:
# 每次操作选择一个 '1'（其右边紧邻 '0'），将其右移越过所有连续 '0' 直到碰到另一个 '1' 或末尾。
# 关键观察：每个 '0' 块（连续的一段 0）会被其左边的每个 '1' 跨越恰好一次。
# 因此，扫描字符串，累计左边出现的 '1' 的数量 ones，
# 每次遇到一个 '0' 块时，将 ones 加到答案中。
#
# 时间复杂度: O(n)
# 空间复杂度: O(1)
#
# 关键点:
# - 每个 0 块作为一个整体，其左边的每个 1 都需要一次操作跨越它
# - 不需要实际模拟移动过程
