#
# Difficulty: Medium
# Tags: String, Dynamic Programming, Prefix Sum
#
# 解题思路:
# 选 3 栋建筑且相邻两栋不能同类型，有效模式只有 "010" 和 "101" 两种。
# 遍历字符串，以每个位置作为中间元素：
# - 若当前为 '0'（中间），则左右各选一个 '1'：方案数 = left1 * right1
# - 若当前为 '1'（中间），则左右各选一个 '0'：方案数 = left0 * right0
# 维护左侧已遍历过的 0/1 数量，右侧数量通过总数减去左侧数得到。
# 累加所有位置的贡献即可。
#
# 时间复杂度: O(n) 一次遍历
# 空间复杂度: O(1) 只使用常量额外空间
#
# 关键点:
# - 只有 "010" 和 "101" 两种有效模式
# - 枚举中间元素，左右相乘即得组合数
# - 前缀计数避免嵌套循环
