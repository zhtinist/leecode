"""
LeetCode #2222 - Number of Ways to Select Buildings
选择建筑的方案数
https://leetcode.cn/problems/number-of-ways-to-select-buildings/

给你一个下标从 0 开始的二进制字符串 `s` ，它表示一条街沿途的建筑类型，其中：
`s[i] = '0'` 表示第 `i` 栋建筑是一栋办公楼，
`s[i] = '1'` 表示第 `i` 栋建筑是一间餐厅。
作为市政厅的官员，你需要随机 选择 3 栋建筑。然而，为了确保多样性，选出来的 3 栋建筑 相邻 的两栋不能是同一类型。
比方说，给你 `s = "001101"` ，我们不能选择第 `1` ，`3` 和 `5` 栋建筑，因为得到的子序列是 `"011"` ，有相邻两栋建筑是同一类型，所以 不合 题意。
请你返回可以选择 3 栋建筑的 有效方案数 。

示例 1：
输入：s = "001101" 输出：6 解释： 以下下标集合是合法的： - [0,2,4] ，从 "001101" 得到 "010" - [0,3,4] ，从 "001101" 得到 "010" - [1,2,4] ，从 "001101" 得到 "010" - [1,3,4] ，从 "001101" 得到 "010" - [2,4,5] ，从 "001101" 得到 "101" - [3,4,5] ，从 "001101" 得到 "101" 没有别的合法选择，所以总共有 6 种方法。
示例 2：
输入：s = "11100" 输出：0 解释：没有任何符合题意的选择。

提示：
`3 <= s.length <= 10^5`
`s[i]` 要么是 `'0'` ，要么是 `'1'` 。
"""

from typing import List, Optional


class Solution:
    def numberOfWays(self, s: str) -> int:
        n = len(s)
        # 统计字符串中 0 和 1 的总数
        total0 = s.count('0')
        total1 = n - total0

        left0 = 0  # 当前位置之前 '0' 的数量
        left1 = 0  # 当前位置之前 '1' 的数量
        ans = 0

        for i, ch in enumerate(s):
            if ch == '0':
                # 当前 '0' 作为中间元素，模式为 "101"
                # 左边选一个 '1'，右边选一个 '1'
                right1 = total1 - left1
                ans += left1 * right1
                left0 += 1
            else:  # ch == '1'
                # 当前 '1' 作为中间元素，模式为 "010"
                # 左边选一个 '0'，右边选一个 '0'
                right0 = total0 - left0
                ans += left0 * right0
                left1 += 1

        return ans


