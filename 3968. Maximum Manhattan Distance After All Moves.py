#
# Difficulty: Medium
# Tags: Math, String, Counting
#
# 解题思路:
# 1. 统计四种固定方向移动的净效果：
#    - 水平方向：x = count('R') - count('L')
#    - 垂直方向：y = count('U') - count('D')
#    - 空白字符 `_` 可以自由选择方向，记为 k 个
# 2. 曼哈顿距离 = |x| + |y|。对于每个下划线，我们需要决定将其分配到
#    哪个方向以最大化最终的 |x'| + |y'|。
# 3. 关键观察：只要分配的方向不使 x 或 y 跨越零点（即符号不变），
#    每增加一个单位位移，曼哈顿距离就严格增加 1。
#    例如当前 x >= 0，分配一个 'R'：|x+1| = x+1 = |x| + 1。
#    若 x < 0，分配一个 'L'：|x-1| = -(x-1) = -x+1 = |x| + 1。
# 4. 由于我们可以将所有下划线分配到与净位移同号的方向（若净位移为 0
#    则任意分配均可），永远不会出现"跨越零导致距离减小"的情况。
# 5. 因此最终答案 = |x| + |y| + k。
#
# 时间复杂度: O(n)，其中 n 为 moves 字符串长度，只需一次遍历
# 空间复杂度: O(1)，仅使用常数个变量
#
# 关键点:
# - 每个下划线独立分配，总能让曼哈顿距离增加 1
# - 只要不改变净位移的符号，距离就一定增加
# - 无需尝试所有分配组合，直接累加即可
