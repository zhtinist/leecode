"""
LeetCode #3968 - Maximum Manhattan Distance After All Moves
移动后的最大曼哈顿距离
https://leetcode.cn/problems/maximum-manhattan-distance-after-all-moves/

给你一个由字符 `'U'`、`'D'`、`'L'`、`'R'` 和 `'_'` 组成的字符串 `moves`。
从原点 `(0, 0)` 出发，每个字符表示二维平面上的一次移动：
`'U'`：向上移动 1 个单位。
`'D'`：向下移动 1 个单位。
`'L'`：向左移动 1 个单位。
`'R'`：向右移动 1 个单位。
`'_'`：可以独立地替换为 `'U'`、`'D'`、`'L'` 或 `'R'` 中的任意一个字符。
返回执行完所有移动后，能够达到的距离原点的 最大曼哈顿距离 。
两点 `(x_1, y_1)` 和 `(x_2, y_2)` 之间的 曼哈顿距离 为 `|x_1 - x_2| + |y_1 - y_2|`。

示例 1：

输入： moves = "L_D_"
输出： 4
解释：
一种最优选择为：
`'L'`：`(0, 0) -> (-1, 0)`
将 `'_'` 视为 `'D'`：`(-1, 0) -> (-1, -1)`
`'D'`：`(-1, -1) -> (-1, -2)`
将 `'_'` 视为 `'L'`：`(-1, -2) -> (-2, -2)`
最终位置到原点的曼哈顿距离为 `|0 - (-2)| + |0 - (-2)| = 4`。
示例 2：

输入： moves = "U_R"
输出： 3
解释：
一种最优选择为：
`'U'`：`(0, 0) -> (0, 1)`
将 `'_'` 视为 `'U'`：`(0, 1) -> (0, 2)`
`'R'`：`(0, 2) -> (1, 2)`
最终位置到原点的曼哈顿距离为 `|0 - 1| + |0 - 2| = 3`。

提示：
`1 <= moves.length <= 10^5`
`moves` 仅由 `'U'`、`'D'`、`'L'`、`'R'` 和 `'_'` 组成。
"""

from typing import List, Optional


class Solution:
    def maxDistance(self, moves: str) -> int:
        """
        计算所有移动后能达到的最大曼哈顿距离。

        统计已有移动产生的净位移：x = R - L, y = U - D。
        每个下划线 `_` 可以独立分配到任意方向。
        关键洞察：只要不跨越零点，每分配一个下划线就能让曼哈顿距离增加 1。
        因为我们总可以将下划线分配到与其净位移符号相同的方向
        （若净位移为 0 则任意方向均可），所以所有下划线都能有效增加距离。
        最终答案 = |x| + |y| + 下划线数量。
        """
        x = 0  # 净水平位移：右为正
        y = 0  # 净垂直位移：上为正
        blank = 0  # 下划线数量

        for ch in moves:
            if ch == 'R':
                x += 1
            elif ch == 'L':
                x -= 1
            elif ch == 'U':
                y += 1
            elif ch == 'D':
                y -= 1
            else:  # '_'
                blank += 1

        return abs(x) + abs(y) + blank










