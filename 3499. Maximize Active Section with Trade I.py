#
# Difficulty: Medium
# Tags: String, Enumeration
#
# 解题思路:
# 1. 两端加 '1' 得到 t = '1' + s + '1'，确保首尾都是 1
# 2. 将 t 解析为交替的 0/1 块序列
# 3. 操作等价于：
#    - 选择一个内部 1-块（两边都有 0-块），将其变为 0（合并三个块为一个大 0-块）
#    - 再将这个大 0-块变为 1
#    - 净收益 = 左侧 0-块大小 + 右侧 0-块大小
# 4. 枚举所有内部 1-块，计算最大收益
# 5. 答案 = 原始 1 的数量 + 最大收益
#
# 时间复杂度: O(n)
# 空间复杂度: O(n)
#
# 关键点:
# - 两端加 1 的 padding 使边界处理统一
# - 只有内部 1-块（两边都是 0-块）才能被"包围"
# - 操作后该 1-块本身不变（0→1 又变回 1），只多了两边的 0 变成 1
