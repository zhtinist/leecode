# 解题思路:
# 博弈论思维题。如果字符串没有元音，Alice 第一回合就无法操作，直接输。
# 只要字符串中至少存在一个元音，Alice 就能获胜：
# - 若元音总数为奇数：Alice 直接移除整个字符串（包含奇数个元音）获胜
# - 若元音总数为偶数：Alice 移除一个含 1 个元音的子串，留下奇数个元音。
#   Bob 需要移除偶数元音的子串，但剩余字符串总元音数为奇数。
#   无论 Bob 如何操作，Alice 总能在下一回合找到含奇数元音的子串。
#   最终 Alice 会拿到最后一手。
#
# 时间复杂度: O(n)
# 空间复杂度: O(1)
#
# 关键点:
# - 只要存在至少一个元音，先手必胜
# - 因为 Alice 可以灵活选择移除任意含奇数元音的子串来控制局面的奇偶性
