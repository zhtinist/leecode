# 解题思路:
# 使用定长滑动窗口（窗口大小 = w）模拟每天的处理过程：
# 1. 维护一个哈希表 cnt，记录当前窗口内每种保留物品类型的出现次数。
# 2. 维护一个布尔数组 discarded，标记每天到达的物品是否被丢弃。
# 3. 对于每天 i：
#    a. 如果 i >= w，第 i-w 天的元素离开窗口：
#       如果该元素未被丢弃，从 cnt 中减 1。
#    b. 对于当天到达的物品，检查其类型在窗口内的计数：
#       - 如果 cnt[item] >= m，必须丢弃（计数 +1，标记为丢弃）
#       - 否则保留（计数 +1）
# 4. 贪心"能保留就保留"的策略是最优的，因为丢弃更早的同类型物品不会比丢弃
#    当天到达的物品更优（窗口向前滑动时，更早的物品会更早离开窗口）。
#
# 时间复杂度: O(n) - 每天 O(1) 操作
# 空间复杂度: O(n) - cnt 哈希表和 discarded 数组
#
# 关键点:
# - 滑动窗口的定长特性：窗口始终包含最近 w 天
# - 贪心策略：尽可能保留，只在必须时丢弃
# - 离开窗口的元素只减不减（未被丢弃的才需要清理）



